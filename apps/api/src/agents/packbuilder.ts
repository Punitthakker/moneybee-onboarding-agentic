import { createHash } from 'node:crypto';
import AdmZip from 'adm-zip';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { DOC_TYPE_LABELS, type AcquirerConfig, type DocType } from '@moneybee/shared';
import type { Ctx } from '../context';
import type { CaseRec, PackFile } from '../db/types';
import { extractPages } from '../util/pdf';

export interface BuiltPack {
  files: PackFile[];
  payload: Record<string, unknown>;
}

/** Acquirers are plugged in behind this interface. buildPack produces files; submit sends them (mock for API submit). */
export interface AcquirerAdapter {
  readonly mode: 'file_pack' | 'api_submit_mock';
  buildPack(ctx: Ctx, c: CaseRec, acquirer: AcquirerConfig): Promise<BuiltPack>;
  submit(ctx: Ctx, c: CaseRec, pack: BuiltPack): Promise<{ mode: string; reference: string | null; isMock: boolean }>;
}

const sha = (b: Buffer) => createHash('sha256').update(b).digest('hex');
const slug = (s: string) => s.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 30) || 'merchant';

export function resolveSource(c: CaseRec, source: string): string {
  if (source === 'case.entityType') return c.entityType ?? '';
  if (source.startsWith('ubo:')) {
    const u = c.ubo?.ubos[Number(source.slice(4))];
    return u ? `${u.name} (${u.basis === 'ownership' ? `${u.effectivePct.toFixed(2)}%` : u.basis.replace(/_/g, ' ')})` : '';
  }
  if (source.startsWith('signatory:')) {
    const s = c.signatories[Number(source.slice(10))] ?? c.directors[Number(source.slice(10))];
    return s ? s.name : '';
  }
  const v = c.fields[source]?.value;
  return v === undefined || v === null ? '' : Array.isArray(v) ? v.join('; ') : String(v);
}

export function namePack(pattern: string, seq: number, docType: string, merchant: string): string {
  return pattern.replace('{seq}', String(seq).padStart(2, '0')).replace('{docType}', docType).replace('{merchant}', slug(merchant));
}

async function buildForm(c: CaseRec, a: AcquirerConfig): Promise<Buffer> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const form = pdf.getForm();
  let page = pdf.addPage([595, 842]);
  page.drawText(a.form.title, { x: 40, y: 800, size: 15, font: bold, color: rgb(0.08, 0.07, 0.05) });
  page.drawText(`Case ${c.ref}  |  generated by MoneyBee Onboard  |  DRAFT for reviewer, not an acquirer-issued form`, { x: 40, y: 784, size: 8, font, color: rgb(0.4, 0.4, 0.4) });
  let y = 750;
  for (const f of a.form.fields) {
    if (y < 60) {
      page = pdf.addPage([595, 842]);
      y = 800;
    }
    page.drawText(f.label, { x: 40, y: y + 16, size: 8, font, color: rgb(0.35, 0.33, 0.3) });
    const tf = form.createTextField(f.name);
    tf.setText(resolveSource(c, f.source));
    tf.addToPage(page, { x: 40, y, width: 515, height: 18, font, borderColor: rgb(0.85, 0.8, 0.7) });
    y -= 40;
  }
  return Buffer.from(await pdf.save());
}

async function buildPackImpl(ctx: Ctx, c: CaseRec, a: AcquirerConfig): Promise<BuiltPack> {
  const files: PackFile[] = [];
  const merchant = c.legalName ?? c.name;
  const put = async (name: string, data: Buffer, kind: PackFile['kind'], docId?: string) => {
    const key = `cases/${c.id}/pack/${name}`;
    await ctx.blobs.put(key, data);
    files.push({ name, key, sha256: sha(data), kind, docId });
  };

  await put(`00_${slug(a.code)}_application_form_${slug(merchant)}.pdf`, await buildForm(c, a), 'form');

  const order = a.documentNaming.order as DocType[];
  const docs = c.documents.filter((d) => d.docType !== 'unknown' && !c.files.find((f) => f.id === d.fileId)?.duplicateOf);
  const sorted = [...docs].sort((x, y) => {
    const ix = order.indexOf(x.docType);
    const iy = order.indexOf(y.docType);
    return (ix < 0 ? 999 : ix) - (iy < 0 ? 999 : iy);
  });
  let seq = 1;
  for (const d of sorted) {
    const f = c.files.find((x) => x.id === d.fileId)!;
    const raw = await ctx.blobs.get(f.storageKey);
    let data = raw;
    let ext = f.mime === 'application/pdf' ? 'pdf' : f.mime === 'image/png' ? 'png' : 'jpg';
    if (f.mime === 'application/pdf' && f.pageCount && (d.pageStart !== 1 || d.pageEnd !== f.pageCount)) data = await extractPages(raw, d.pageStart, d.pageEnd);
    const name = `${namePack(a.documentNaming.pattern, seq++, d.docType, merchant)}.${ext}`;
    await put(name, data, 'document', d.id);
  }

  const payload = {
    acquirerCode: a.code,
    caseRef: c.ref,
    generatedAt: ctx.now().toISOString(),
    isExampleAcquirer: a.example,
    entityType: c.entityType,
    form: Object.fromEntries(a.form.fields.map((f) => [f.name, resolveSource(c, f.source)])),
    ubos: c.ubo?.ubos ?? [],
    directors: c.directors,
    signatories: c.signatories,
    documents: files.filter((f) => f.kind === 'document').map((f) => ({ name: f.name, sha256: f.sha256, label: DOC_TYPE_LABELS[(c.documents.find((d) => d.id === f.docId)?.docType ?? 'unknown') as DocType] })),
    risk: c.risk ? { rating: c.risk.rating, score: c.risk.score, reasonCodes: c.risk.reasonCodes } : null,
  };
  await put(`payload_${slug(merchant)}.json`, Buffer.from(JSON.stringify(payload, null, 2)), 'payload');

  const zip = new AdmZip();
  for (const f of files) zip.addFile(f.name, await ctx.blobs.get(f.key));
  await put(`pack_${slug(merchant)}.zip`, zip.toBuffer(), 'archive');
  return { files, payload };
}

export const filePackAdapter: AcquirerAdapter = {
  mode: 'file_pack',
  buildPack: buildPackImpl,
  async submit() {
    return { mode: 'file_pack', reference: null, isMock: false };
  },
};

/** MOCK: no acquirer API is called. See docs/MOCKS.md. */
export const apiSubmitMockAdapter: AcquirerAdapter = {
  mode: 'api_submit_mock',
  buildPack: buildPackImpl,
  async submit(_ctx, c) {
    return { mode: 'api_submit_mock', reference: `MOCK-${c.ref}`, isMock: true };
  },
};
